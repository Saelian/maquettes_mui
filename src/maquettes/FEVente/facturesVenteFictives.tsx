import { FactureVente } from '../FacturesVenteIxfacture';

// Interface pour une ligne de facture de vente
export interface LigneFactureVente {
  numeroLigne: number;
  designation: string;
  quantite: number;
  unite: string; // Unité (ex: "pièce", "heure", "jour", "forfait")
  prixUnitaireHT: number;
  montantHT: number;
  tauxTVA: number;
  montantTVA: number;
  montantTTC: number;
}

// Fonction helper pour créer une ligne de facture de vente
export const creerLigneFacture = (
  numero: number,
  designation: string,
  quantite: number,
  unite: string,
  prixUnitaireHT: number,
  tauxTVA: number
): LigneFactureVente => {
  const montantHT = Math.round(quantite * prixUnitaireHT * 100) / 100;
  const montantTVA = Math.round(montantHT * (tauxTVA / 100) * 100) / 100;
  const montantTTC = Math.round((montantHT + montantTVA) * 100) / 100;

  return {
    numeroLigne: numero,
    designation,
    quantite,
    unite,
    prixUnitaireHT,
    montantHT,
    tauxTVA,
    montantTVA,
    montantTTC,
  };
};

