// Fonction helper pour créer des lignes de facture
export const creerLigneFactureAchat = (
  numero: number,
  nom: string,
  quantite: number,
  prixUnitaireNet: number,
  tauxTVA: number
): LigneFacture => {
  const montantNet = arrondirMontant(quantite * prixUnitaireNet);
  return {
    numeroLigne: numero,
    article: {
      nom,
    },
    quantite,
    uniteMesure: 'C62', // Code UN/ECE pour "unité"
    prixUnitaireNet,
    montantNet,
    informationTVA: {
      codeCategorie: 'S',
      taux: tauxTVA,
    },
  };
};

